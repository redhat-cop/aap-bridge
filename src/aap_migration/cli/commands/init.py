"""Interactive workspace setup for AAP Bridge.

``aap-bridge init`` creates a self-contained working directory holding the
``.env``, ``config/config.yaml``, and artifact directories a migration needs.
It is the entry point for an installed, source-free CLI: nothing outside this
directory is written, and no repository checkout is required.

The installer scripts under ``scripts/`` call this command as their final step.
"""

from __future__ import annotations

import base64
import os
import re
import secrets
import shutil
from pathlib import Path
from urllib.parse import quote

import click

from aap_migration.cli import diagnostics, ui
from aap_migration.resources import SUPPORTED_SOURCE_VERSIONS, SUPPORTED_TARGET_VERSIONS

#: Directories a migration writes into, created inside the workspace.
_ARTIFACT_DIRS = ("exports", "xformed", "reports", "logs", "schemas", "backups")

#: Port the bundled compose PostgreSQL service publishes on the host. Every
#: published port is configurable, so a machine already running PostgreSQL on
#: the default does not have to give it up.
_DEFAULT_DB_PORT = 15432


def _bundled_db_port() -> int:
    """The host port for the bundled database, from the environment or default."""
    raw = os.environ.get("AAP_BRIDGE_DB_PORT", "")
    return int(raw) if raw.isdigit() else _DEFAULT_DB_PORT


_BUNDLED_DB_NAME = "aap_migration"
_BUNDLED_DB_USER = "aap_migration_user"

_CONFIG_TEMPLATE = """\
# AAP Bridge configuration
#
# Generated by `aap-bridge init`. Endpoints and tokens live in the sibling
# .env file; this file only references them.
#
# Every other setting (performance tuning, validation, logging, batch sizes)
# uses a built-in default. Add sections here only to override one. See:
# https://redhat-cop.github.io/aap-bridge/getting-started/configuration/

source:
  url: ${SOURCE__URL}
  version: ${SOURCE__VERSION}
  verify_ssl: ${SOURCE__VERIFY_SSL}
  timeout: ${SOURCE__TIMEOUT}

target:
  url: ${TARGET__URL}
  version: ${TARGET__VERSION}
  verify_ssl: ${TARGET__VERIFY_SSL}
  timeout: ${TARGET__TIMEOUT}

state:
  # Migration state database connection string, from .env
  db_path: ${MIGRATION_STATE_DB_PATH}
"""

